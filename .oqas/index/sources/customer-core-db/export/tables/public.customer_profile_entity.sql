CREATE TABLE public.customer_profile_entity (
  birthday timestamp(6) without time zone,
  current_address_id bigint,
  id bigint GENERATED BY DEFAULT AS IDENTITY NOT NULL,
  email character varying(255),
  firstname character varying(255),
  lastname character varying(255),
  phone_number character varying(255),
  PRIMARY KEY (id),
  FOREIGN KEY (current_address_id) REFERENCES public.addresses (id),
  CONSTRAINT customer_profile_entity_current_address_id_key UNIQUE (current_address_id)
);
